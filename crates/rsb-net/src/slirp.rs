/// Default virtual gateway IPv4 address (`10.0.2.2`).
pub const GATEWAY_IP: Ipv4Addr = Ipv4Addr::new(10, 0, 2, 2);
/// Default guest sandbox IPv4 address (`10.0.2.15`).
pub const GUEST_IP: Ipv4Addr = Ipv4Addr::new(10, 0, 2, 15);
/// Default virtual gateway MAC address.
pub const GATEWAY_MAC: [u8; 6] = [0x02, 0x00, 0x00, 0x00, 0x00, 0x02];

/// Counters exposed by `SlirpBridge` for observability and testing.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct BridgeStats {
    pub dns_allowed: u64,
    pub dns_blocked: u64,
    pub tcp_allowed: u64,
    pub tcp_blocked: u64,
    pub sni_blocked: u64,
}

/// Queue-backed Ethernet `smoltcp::phy::Device` that can be driven by either a real
/// Linux TAP FD or an in-memory virtual wire (for deterministic tests).
pub struct QueueEthernetDevice {
    rx_queue: VecDeque<Vec<u8>>,
    tx_queue: VecDeque<Vec<u8>>,
    mtu: usize,
}

impl QueueEthernetDevice {
    pub fn new(mtu: usize) -> Self {
        Self {
            rx_queue: VecDeque::new(),
            tx_queue: VecDeque::new(),
            mtu,
        }
    }

    /// Push a raw Ethernet frame received from the guest (or TAP FD).
    pub fn push_rx(&mut self, frame: Vec<u8>) {
        self.rx_queue.push_back(frame);
    }

    /// Pop a raw Ethernet frame generated by `smoltcp` to send back to the guest (or TAP FD).
    pub fn pop_tx(&mut self) -> Option<Vec<u8>> {
        self.tx_queue.pop_front()
    }
}

pub struct QueueRxToken(Vec<u8>);

impl RxToken for QueueRxToken {
    fn consume<R, F>(self, f: F) -> R
    where
        F: FnOnce(&[u8]) -> R,
    {
        f(&self.0)
    }
}

pub struct QueueTxToken<'a>(&'a mut VecDeque<Vec<u8>>);

impl<'a> TxToken for QueueTxToken<'a> {
    fn consume<R, F>(self, len: usize, f: F) -> R
    where
        F: FnOnce(&mut [u8]) -> R,
    {
        let mut buf = vec![0u8; len];
        let res = f(&mut buf);
        self.0.push_back(buf);
        res
    }
}

impl Device for QueueEthernetDevice {
    type RxToken<'a> = QueueRxToken;
    type TxToken<'a> = QueueTxToken<'a>;

    fn receive(&mut self, _ts: SmolInstant) -> Option<(Self::RxToken<'_>, Self::TxToken<'_>)> {
        let frame = self.rx_queue.pop_front()?;
        Some((QueueRxToken(frame), QueueTxToken(&mut self.tx_queue)))
    }

    fn transmit(&mut self, _ts: SmolInstant) -> Option<Self::TxToken<'_>> {
        Some(QueueTxToken(&mut self.tx_queue))
    }

    fn capabilities(&self) -> DeviceCapabilities {
        let mut caps = DeviceCapabilities::default();
        caps.medium = Medium::Ethernet;
        caps.max_transmission_unit = self.mtu;
        caps
    }
}

enum UpstreamState {
    Idle,
    Connecting(Receiver<io::Result<TcpStream>>),
    Connected(TcpStream),
    Closed,
}

struct WorkerGuard(Arc<AtomicUsize>);

impl Drop for WorkerGuard {
    fn drop(&mut self) {
        self.0.fetch_sub(1, Ordering::Relaxed);
    }
}

struct ActiveTcpConn {
    handle: SocketHandle,
    dst_ip: Ipv4Addr,
    dst_port: u16,
    pending_syn: Option<(Ipv4Addr, u16)>,
    validated_domains: Vec<String>,
    sni_checked: bool,
    sni_buf: Vec<u8>,
    tx_pending: VecDeque<u8>,
    guest_eof_sent: bool,
    upstream: UpstreamState,
    last_activity: Instant,
}

struct AsyncDnsReply {
    meta: udp::UdpMetadata,
    qname: String,
    resolved_ips: Vec<Ipv4Addr>,
    response_bytes: Vec<u8>,
}

const DNS_CACHE_TTL: Duration = Duration::from_secs(300);
const MAX_BG_WORKERS: usize = 32;
const CONN_IDLE_TIMEOUT: Duration = Duration::from_secs(60);

/// Transparent L2/L3 `smoltcp` userspace network bridge enforcing [`EgressPolicy`].
pub struct SlirpBridge {
    pub policy: EgressPolicy,
    pub stats: BridgeStats,
    pub device: QueueEthernetDevice,
    iface: Interface,
    sockets: SocketSet<'static>,
    dns_handle: SocketHandle,
    dns_tx: Sender<AsyncDnsReply>,
    dns_rx: Receiver<AsyncDnsReply>,
    /// Multi-domain TTL cache (`ip -> [(domain, expires_at)]`) so shared CDN IPs
    /// serving multiple allowed domains never overwrite each other's SNI validation.
    dns_cache: HashMap<Ipv4Addr, Vec<(String, Instant)>>,
    tcp_conns: Vec<ActiveTcpConn>,
    bg_workers: Arc<std::sync::atomic::AtomicUsize>,
    egress_window_start: Instant,
    egress_window_bytes: u64,
    #[cfg(test)]
    upstream_override: Option<SocketAddr>,
}

impl SlirpBridge {
    /// Create a new `SlirpBridge` virtual gateway (`10.0.2.2/24`, `any_ip = true`).
    pub fn new(policy: EgressPolicy) -> Self {
        let mut device = QueueEthernetDevice::new(1500);
        let cfg = Config::new(EthernetAddress(GATEWAY_MAC).into());
        let mut iface = Interface::new(cfg, &mut device, SmolInstant::from_millis(0));
        iface.update_ip_addrs(|addrs| {
            let _ = addrs.push(IpCidr::new(IpAddress::Ipv4(GATEWAY_IP), 24));
        });
        // `any_ip = true` + default route pointing to `GATEWAY_IP` allows smoltcp
        // to transparently terminate TCP/UDP for ANY remote IPv4 destination!
        let _ = iface.routes_mut().add_default_ipv4_route(GATEWAY_IP);
        iface.set_any_ip(true);

        let mut sockets = SocketSet::new(Vec::new());

        // Bind built-in UDP/53 DNS filter socket
        let dns_rx = udp::PacketBuffer::new(vec![udp::PacketMetadata::EMPTY; 16], vec![0; 4096]);
        let dns_tx = udp::PacketBuffer::new(vec![udp::PacketMetadata::EMPTY; 16], vec![0; 4096]);
        let mut dns_sock = udp::Socket::new(dns_rx, dns_tx);
        let _ = dns_sock.bind((IpAddress::Ipv4(GATEWAY_IP), 53));
        let dns_handle = sockets.add(dns_sock);

        let (dns_tx, dns_rx) = mpsc::channel();

        Self {
            policy,
            stats: BridgeStats::default(),
            device,
            iface,
            sockets,
            dns_handle,
            dns_tx,
            dns_rx,
            dns_cache: HashMap::new(),
            tcp_conns: Vec::new(),
            bg_workers: Arc::new(std::sync::atomic::AtomicUsize::new(0)),
            egress_window_start: Instant::now(),
            egress_window_bytes: 0,
            #[cfg(test)]
            upstream_override: None,
        }
    }

    /// Feed a raw Ethernet frame from the sandbox (TAP FD or virtual wire) into the bridge.
    ///
    /// Performs L3/L4 `EgressPolicy` inspection on TCP `SYN` frames *before* `smoltcp`
    /// even sees them, so disallowed destinations are dropped with zero host socket activity.
    pub fn ingest_guest_frame(&mut self, frame: Vec<u8>) {
        if let Some((src_ip, src_port, dst_ip, dst_port)) = inspect_tcp_syn(&frame) {
            let now = Instant::now();
            let cached_domains: Vec<String> = self
                .dns_cache
                .get(&dst_ip)
                .map(|entries| {
                    entries
                        .iter()
                        .filter(|(_, exp)| *exp > now)
                        .map(|(d, _)| d.clone())
                        .collect()
                })
                .unwrap_or_default();

            let allowed_domains: Vec<String> = cached_domains
                .into_iter()
                .filter(|d| {
                    self.policy
                        .check_ip(IpAddr::V4(dst_ip), dst_port, Some(d))
                        .is_allowed()
                })
                .collect();

            let allowed = if !allowed_domains.is_empty() {
                true
            } else {
                self.policy
                    .check_ip(IpAddr::V4(dst_ip), dst_port, None)
                    .is_allowed()
            };

            if !allowed {
                self.stats.tcp_blocked += 1;
                // Silently drop SYN — host never touches the network!
                return;
            }
            self.stats.tcp_allowed += 1;
            self.ensure_tcp_listener(src_ip, src_port, dst_ip, dst_port, allowed_domains);
        }

        self.device.push_rx(frame);
    }

    /// Advance the `smoltcp` state machine, process DNS queries, and relay active TCP streams.
    pub fn poll(&mut self, now_ms: i64) {
        let ts = SmolInstant::from_millis(now_ms);
        self.iface.poll(ts, &mut self.device, &mut self.sockets);
        self.process_dns();
        self.relay_tcp_streams();
        // Second poll flushes any generated DNS/TCP TX frames immediately
        self.iface.poll(ts, &mut self.device, &mut self.sockets);
    }

    /// Pop the next outbound Ethernet frame destined for the guest TAP device.
    pub fn next_host_frame(&mut self) -> Option<Vec<u8>> {
        self.device.pop_tx()
    }

    /// Spawn a background thread driving this `SlirpBridge` over a live Linux TAP FD
    /// (received from a rootless `CLONE_NEWNET` child via `SCM_RIGHTS`).
    pub fn spawn_on_tap(mut self, tap_fd: OwnedFd) -> io::Result<SlirpHandle> {
        use rsb_sys::rustix::event::{PollFd, PollFlags, Timespec, poll};
        use rsb_sys::rustix::fs::{OFlags, fcntl_getfl, fcntl_setfl};
        use rsb_sys::rustix::io::{Errno, read, write};

        let flags = fcntl_getfl(&tap_fd)
            .map_err(|e| io::Error::from_raw_os_error(e.raw_os_error()))?;
        fcntl_setfl(&tap_fd, flags | OFlags::NONBLOCK)
            .map_err(|e| io::Error::from_raw_os_error(e.raw_os_error()))?;

        let shutdown = Arc::new(AtomicBool::new(false));
        let shutdown_bg = Arc::clone(&shutdown);

        let handle = thread::spawn(move || {
            let start = Instant::now();
            let mut rx_buf = [0u8; 2048];
            let ts = Timespec {
                tv_sec: 0,
                tv_nsec: 5_000_000, // 5ms poll tick
            };

            let mut tx_retry: VecDeque<Vec<u8>> = VecDeque::new();
            while !shutdown_bg.load(Ordering::Relaxed) {
                let events = if tx_retry.is_empty() {
                    PollFlags::IN
                } else {
                    PollFlags::IN | PollFlags::OUT
                };
                let mut pfds = [PollFd::new(&tap_fd, events)];
                let _ = poll(&mut pfds, Some(&ts));

                // Drain up to 64 Ethernet frames per tick when outbound backpressure allows,
                // so a guest packet flood cannot starve `self.poll()` or drop outbound frames.
                if tx_retry.len() < 256 {
                    for _ in 0..64 {
                        match read(&tap_fd, &mut rx_buf) {
                            Ok(0) => return self.stats,
                            Ok(n) => self.ingest_guest_frame(rx_buf[..n].to_vec()),
                            Err(Errno::AGAIN | Errno::INTR) => break,
                            Err(_) => return self.stats,
                        }
                    }
                }

                let now_ms = start.elapsed().as_millis() as i64;
                self.poll(now_ms);

                // Flush outbound Ethernet frames, re-queuing on EAGAIN instead of dropping.
                while tx_retry.len() < 256 {
                    let Some(frame) = self.next_host_frame() else {
                        break;
                    };
                    tx_retry.push_back(frame);
                }
                while let Some(frame) = tx_retry.front() {
                    match write(&tap_fd, frame) {
                        Ok(_) => {
                            tx_retry.pop_front();
                        }
                        Err(Errno::AGAIN) => break,
                        Err(Errno::INTR) => continue,
                        Err(_) => {
                            tx_retry.pop_front();
                        }
                    }
                }
            }
            self.stats
        });

        Ok(SlirpHandle {
            shutdown,
            handle: Some(handle),
        })
    }

    fn ensure_tcp_listener(
        &mut self,
        src_ip: Ipv4Addr,
        src_port: u16,
        dst_ip: Ipv4Addr,
        dst_port: u16,
        validated_domains: Vec<String>,
    ) {
        // Cap concurrent TCP flows to prevent host OOM from guest SYN floods.
        const MAX_TCP_CONNS: usize = 128;
        if self.tcp_conns.len() >= MAX_TCP_CONNS {
            return;
        }
        // Only deduplicate SYN retransmits for the exact same 4-tuple so concurrent
        // connections to the same (dst_ip, dst_port) in the same batch each get a
        // listening socket and are not rejected with TCP RST.
        for c in &mut self.tcp_conns {
            let sock = self.sockets.get::<tcp::Socket>(c.handle);
            if c.dst_ip == dst_ip
                && c.dst_port == dst_port
                && sock.state() == tcp::State::Listen
                && c.pending_syn == Some((src_ip, src_port))
            {
                for d in validated_domains {
                    if !c.validated_domains.iter().any(|e| e.eq_ignore_ascii_case(&d)) {
                        c.validated_domains.push(d);
                    }
                }
                return;
            }
        }

        let rx_buf = tcp::SocketBuffer::new(vec![0u8; 32 * 1024]);
        let tx_buf = tcp::SocketBuffer::new(vec![0u8; 32 * 1024]);
        let mut sock = tcp::Socket::new(rx_buf, tx_buf);
        let endpoint = (IpAddress::Ipv4(dst_ip), dst_port);
        if sock.listen(endpoint).is_ok() {
            let handle = self.sockets.add(sock);
            self.tcp_conns.push(ActiveTcpConn {
                handle,
                dst_ip,
                dst_port,
                pending_syn: Some((src_ip, src_port)),
                validated_domains,
                sni_checked: false,
                sni_buf: Vec::new(),
                tx_pending: VecDeque::new(),
                guest_eof_sent: false,
                upstream: UpstreamState::Idle,
                last_activity: Instant::now(),
            });
        }
    }

    fn process_dns(&mut self) {
        let mut immediate_replies: Vec<(udp::UdpMetadata, Vec<u8>)> = Vec::new();
        {
            let sock = self.sockets.get_mut::<udp::Socket>(self.dns_handle);
            while let Ok((data, meta)) = sock.recv() {
                let Some(q) = parse_dns_query(data) else {
                    continue;
                };
                if !self.policy.check_domain(&q.qname, None).is_allowed() {
                    self.stats.dns_blocked += 1;
                    immediate_replies.push((meta, build_dns_refused(data, &q)));
                    continue;
                }
                self.stats.dns_allowed += 1;
                // Only IPv4 (`A` = 1 or `ANY` = 255) is routed over the IPv4 TAP bridge;
                // for `AAAA` (28), `HTTPS` (65), etc., reply immediately with NOERROR + 0 answers
                // so dual-stack resolvers (glibc/curl) do not stall or reject mismatched A records.
                if q.qtype != 1 && q.qtype != 255 {
                    immediate_replies.push((meta, build_dns_a_response(data, &q, &[])));
                    continue;
                }
                // Offload blocking host DNS resolution to a bounded background worker so the
                // SlirpBridge poll loop is never stalled and a guest flood cannot exhaust threads.
                if self.bg_workers.load(Ordering::Relaxed) >= MAX_BG_WORKERS {
                    immediate_replies.push((meta, build_dns_refused(data, &q)));
                    continue;
                }
                self.bg_workers.fetch_add(1, Ordering::Relaxed);
                let guard = WorkerGuard(Arc::clone(&self.bg_workers));
                let raw_query = data.to_vec();
                let fallback_refused = build_dns_refused(data, &q);
                let policy = self.policy.clone();
                let tx = self.dns_tx.clone();
                let spawned = thread::Builder::new()
                    .name("rsb-slirp-dns".into())
                    .spawn(move || {
                        let _guard = guard;
                        let mut allowed_v4 = Vec::new();
                        if let Ok(addrs) = (q.qname.as_str(), 0u16).to_socket_addrs() {
                            for sa in addrs {
                                if let IpAddr::V4(v4) = sa.ip()
                                    && (!policy.block_private_ips
                                        || !crate::policy::is_private_or_metadata(IpAddr::V4(v4)))
                                {
                                    allowed_v4.push(v4);
                                }
                            }
                        }
                        let response_bytes = if allowed_v4.is_empty() {
                            build_dns_refused(&raw_query, &q)
                        } else {
                            build_dns_a_response(&raw_query, &q, &allowed_v4)
                        };
                        let _ = tx.send(AsyncDnsReply {
                            meta,
                            qname: q.qname,
                            resolved_ips: allowed_v4,
                            response_bytes,
                        });
                    });
                if spawned.is_err() {
                    immediate_replies.push((meta, fallback_refused));
                }
            }
        }

        // Drain completed async DNS lookups and update multi-domain TTL `dns_cache`
        let now = Instant::now();
        let expires = now + DNS_CACHE_TTL;
        while let Ok(reply) = self.dns_rx.try_recv() {
            if self.dns_cache.len() >= 1024 {
                self.dns_cache.retain(|_, entries| {
                    entries.retain(|(_, exp)| *exp > now);
                    !entries.is_empty()
                });
                if self.dns_cache.len() >= 1024
                    && let Some(oldest_ip) = self
                        .dns_cache
                        .iter()
                        .min_by_key(|(_, entries)| {
                            entries.iter().map(|(_, exp)| *exp).max().unwrap_or(now)
                        })
                        .map(|(&ip, _)| ip)
                {
                    self.dns_cache.remove(&oldest_ip);
                }
            }
            for ip in reply.resolved_ips {
                let entries = self.dns_cache.entry(ip).or_default();
                entries.retain(|(d, exp)| *exp > now && !d.eq_ignore_ascii_case(&reply.qname));
                if entries.len() >= 16 {
                    entries.remove(0);
                }
                entries.push((reply.qname.clone(), expires));
            }
            immediate_replies.push((reply.meta, reply.response_bytes));
        }

        let sock = self.sockets.get_mut::<udp::Socket>(self.dns_handle);
        for (meta, resp) in immediate_replies {
            let _ = sock.send_slice(&resp, meta);
        }
    }

    fn relay_tcp_streams(&mut self) {
        let mut to_remove = Vec::new();
        let mut tmp = [0u8; 4096];
        let now = Instant::now();

        if now.duration_since(self.egress_window_start) >= Duration::from_secs(1) {
            self.egress_window_start = now;
            self.egress_window_bytes = 0;
        }

        for (idx, conn) in self.tcp_conns.iter_mut().enumerate() {
            let sock = self.sockets.get_mut::<tcp::Socket>(conn.handle);

            // Clean up fully closed sockets
            if sock.state() == tcp::State::Closed {
                to_remove.push(idx);
                continue;
            }

            // Evict lingering half-open / idle sockets to prevent resource exhaustion
            if now.duration_since(conn.last_activity) > CONN_IDLE_TIMEOUT {
                sock.abort();
                conn.upstream = UpstreamState::Closed;
                continue;
            }

            // 1. Poll any in-flight non-blocking upstream TCP connect
            if let UpstreamState::Connecting(ref rx) = conn.upstream {
                match rx.try_recv() {
                    Ok(Ok(stream)) => {
                        let _ = stream.set_nonblocking(true);
                        conn.upstream = UpstreamState::Connected(stream);
                        conn.last_activity = now;
                    }
                    Ok(Err(_)) | Err(mpsc::TryRecvError::Disconnected) => {
                        // Let the next `iface.poll()` emit TCP RST before reaping on Closed
                        sock.abort();
                        conn.upstream = UpstreamState::Closed;
                        continue;
                    }
                    Err(mpsc::TryRecvError::Empty) => {}
                }
            }

            // 2. Guest -> Host relay (bounded `tx_pending` for TCP backpressure, plus
            //    TLS ClientHello SNI verification up to MAX_CLIENT_HELLO_BYTES on port 443 and any TLS port)
            const MAX_TX_PENDING: usize = 64 * 1024;
            if !matches!(conn.upstream, UpstreamState::Closed)
                && sock.can_recv()
                && conn.tx_pending.len() < MAX_TX_PENDING
            {
                let recv_bytes: Vec<u8> = sock
                    .recv(|buf| {
                        let copy = buf.to_vec();
                        (buf.len(), copy)
                    })
                    .unwrap_or_default();

                if !recv_bytes.is_empty() {
                    conn.last_activity = now;
                    let needs_sni = !conn.sni_checked
                        && self.policy.verify_tls_sni
                        && !conn.validated_domains.is_empty();

                    if needs_sni {
                        conn.sni_buf.extend_from_slice(&recv_bytes);
                        let is_tls = conn.sni_buf[0] == 0x16
                            && (conn.sni_buf.len() < 2 || conn.sni_buf[1] == 0x03);
                        let ready = conn.sni_buf.len() >= MAX_CLIENT_HELLO_BYTES
                            || !is_tls
                            || tls_record_expected_len(&conn.sni_buf)
                                .is_some_and(|need| conn.sni_buf.len() >= need.min(MAX_CLIENT_HELLO_BYTES));

                        if ready {
                            conn.sni_checked = true;
                            let is_tls_handshake = conn.sni_buf.len() >= 2
                                && conn.sni_buf[0] == 0x16
                                && conn.sni_buf[1] == 0x03;
                            if conn.dst_port == 443 || is_tls_handshake {
                                let valid = match extract_tls_sni(&conn.sni_buf) {
                                    Some(ref sni) => {
                                        conn.validated_domains.iter().any(|expected| {
                                            sni.eq_ignore_ascii_case(expected.trim_end_matches('.'))
                                        }) && self
                                            .policy
                                            .check_domain(sni, Some(conn.dst_port))
                                            .is_allowed()
                                    }
                                    None => false,
                                };
                                if !valid {
                                    self.stats.sni_blocked += 1;
                                    sock.abort();
                                    conn.upstream = UpstreamState::Closed;
                                    continue;
                                }
                            }
                            conn.tx_pending.extend(conn.sni_buf.drain(..));
                        }
                    } else {
                        conn.sni_checked = true;
                        conn.tx_pending.extend(recv_bytes);
                    }
                }
            }

            // 3. Initiate async upstream connect:
            //    - On port 443 with SNI enforcement, wait for ClientHello SNI check first.
            //    - On all other ports (or without SNI), connect immediately on Established/CloseWait
            //      so server-speaks-first protocols (SSH, SMTP, IMAP, MySQL) never deadlock,
            //      while step 2 still enforces SNI on the first guest->host bytes if TLS is spoken.
            let wait_for_sni = conn.dst_port == 443
                && self.policy.verify_tls_sni
                && !conn.validated_domains.is_empty();
            let ready_to_connect = if wait_for_sni {
                conn.sni_checked && !conn.tx_pending.is_empty()
            } else {
                matches!(sock.state(), tcp::State::Established | tcp::State::CloseWait)
            };
            if ready_to_connect && matches!(conn.upstream, UpstreamState::Idle) {
                if self.bg_workers.load(Ordering::Relaxed) >= MAX_BG_WORKERS {
                    continue;
                }
                self.bg_workers.fetch_add(1, Ordering::Relaxed);
                let guard = WorkerGuard(Arc::clone(&self.bg_workers));

                #[cfg(test)]
                let addr = self
                    .upstream_override
                    .unwrap_or_else(|| SocketAddr::new(IpAddr::V4(conn.dst_ip), conn.dst_port));
                #[cfg(not(test))]
                let addr = SocketAddr::new(IpAddr::V4(conn.dst_ip), conn.dst_port);

                let (tx, rx) = mpsc::channel();
                let spawned = thread::Builder::new()
                    .name("rsb-slirp-tcp".into())
                    .spawn(move || {
                        let _guard = guard;
                        let _ = tx.send(TcpStream::connect_timeout(&addr, Duration::from_secs(3)));
                    });
                if spawned.is_ok() {
                    conn.upstream = UpstreamState::Connecting(rx);
                } else {
                    sock.abort();
                    conn.upstream = UpstreamState::Closed;
                }
            }

            // 4. Flush pending guest->host bytes (with optional egress bandwidth throttle)
            if let UpstreamState::Connected(ref mut up) = conn.upstream {
                while !conn.tx_pending.is_empty() {
                    if let Some(cap) = self.policy.max_egress_bps
                        && self.egress_window_bytes >= cap
                    {
                        break;
                    }
                    let (front, _) = conn.tx_pending.as_slices();
                    let to_write = if let Some(cap) = self.policy.max_egress_bps {
                        let rem = usize::try_from(cap.saturating_sub(self.egress_window_bytes))
                            .unwrap_or(usize::MAX);
                        &front[..front.len().min(rem.max(1))]
                    } else {
                        front
                    };
                    match up.write(to_write) {
                        Ok(0) => {
                            sock.close();
                            conn.tx_pending.clear();
                            conn.upstream = UpstreamState::Closed;
                            break;
                        }
                        Ok(n) => {
                            conn.tx_pending.drain(..n);
                            self.egress_window_bytes = self.egress_window_bytes.saturating_add(n as u64);
                            conn.last_activity = now;
                        }
                        Err(e) if e.kind() == io::ErrorKind::WouldBlock => break,
                        Err(e) if e.kind() == io::ErrorKind::Interrupted => continue,
                        Err(_) => {
                            sock.close();
                            conn.tx_pending.clear();
                            conn.upstream = UpstreamState::Closed;
                            break;
                        }
                    }
                }
            }

            // Propagate guest half-close (FIN / CloseWait) to upstream once pending writes drain
            if sock.state() == tcp::State::CloseWait
                && conn.tx_pending.is_empty()
                && !conn.guest_eof_sent
                && let UpstreamState::Connected(ref mut up) = conn.upstream
            {
                let _ = up.shutdown(Shutdown::Write);
                conn.guest_eof_sent = true;
            }

            // 5. Host -> Guest relay: cap `up.read` to smoltcp's free TX capacity so
            //    `sock.send_slice` NEVER drops partial bytes and corrupts TLS/TCP streams!
            if let UpstreamState::Connected(ref mut up) = conn.upstream
                && sock.can_send()
            {
                let free = sock.send_capacity().saturating_sub(sock.send_queue());
                let max_read = free.min(tmp.len());
                if max_read > 0 {
                    match up.read(&mut tmp[..max_read]) {
                        Ok(0) => {
                            sock.close();
                            conn.upstream = UpstreamState::Closed;
                        }
                        Ok(n) => {
                            let _ = sock.send_slice(&tmp[..n]);
                            conn.last_activity = now;
                        }
                        Err(e) if e.kind() == io::ErrorKind::WouldBlock => {}
                        Err(_) => {
                            sock.abort();
                            conn.upstream = UpstreamState::Closed;
                        }
                    }
                }
            }
        }

        for idx in to_remove.into_iter().rev() {
            let conn = self.tcp_conns.swap_remove(idx);
            self.sockets.remove(conn.handle);
        }
    }
}

/// Handle to a running background `SlirpBridge` thread attached to a live TAP device.
pub struct SlirpHandle {
    shutdown: Arc<AtomicBool>,
    handle: Option<JoinHandle<BridgeStats>>,
}

impl SlirpHandle {
    /// Stop the TAP bridge thread and return final traffic/policy counters.
    pub fn stop(mut self) -> BridgeStats {
        self.shutdown.store(true, Ordering::Relaxed);
        self.handle
            .take()
            .and_then(|h| h.join().ok())
            .unwrap_or_default()
    }
}

impl Drop for SlirpHandle {
    fn drop(&mut self) {
        self.shutdown.store(true, Ordering::Relaxed);
        if let Some(h) = self.handle.take() {
            let _ = h.join();
        }
    }
}

/// Inspect a raw Ethernet frame; if it is an IPv4 TCP `SYN` (without `ACK`),
/// return `Some((src_ip, src_port, dst_ip, dst_port))`.
fn inspect_tcp_syn(frame: &[u8]) -> Option<(Ipv4Addr, u16, Ipv4Addr, u16)> {
    let eth = EthernetFrame::new_checked(frame).ok()?;
    if eth.ethertype() != EthernetProtocol::Ipv4 {
        return None;
    }
    let ipv4 = Ipv4Packet::new_checked(eth.payload()).ok()?;
    if ipv4.next_header() != IpProtocol::Tcp {
        return None;
    }
    let tcp_pkt = TcpPacket::new_checked(ipv4.payload()).ok()?;
    if tcp_pkt.syn() && !tcp_pkt.ack() {
        return Some((
            ipv4.src_addr(),
            tcp_pkt.src_port(),
            ipv4.dst_addr(),
            tcp_pkt.dst_port(),
        ));
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::net::TcpListener;
    use std::thread;

    /// Build a simulated guest `smoltcp` stack (`10.0.2.15/24`, default gw `10.0.2.2`).
    fn make_guest() -> (QueueEthernetDevice, Interface, SocketSet<'static>) {
        let mut dev = QueueEthernetDevice::new(1500);
        let cfg = Config::new(EthernetAddress([0x02, 0x00, 0x00, 0x00, 0x00, 0x15]).into());
        let mut iface = Interface::new(cfg, &mut dev, SmolInstant::from_millis(0));
        iface.update_ip_addrs(|addrs| {
            let _ = addrs.push(IpCidr::new(IpAddress::Ipv4(GUEST_IP), 24));
        });
        iface
            .routes_mut()
            .add_default_ipv4_route(GATEWAY_IP)
            .unwrap();
        (dev, iface, SocketSet::new(Vec::new()))
    }

    fn pump(
        guest_dev: &mut QueueEthernetDevice,
        guest_iface: &mut Interface,
        guest_socks: &mut SocketSet<'static>,
        bridge: &mut SlirpBridge,
        t_ms: i64,
    ) {
        let ts = SmolInstant::from_millis(t_ms);
        guest_iface.poll(ts, guest_dev, guest_socks);
        while let Some(f) = guest_dev.pop_tx() {
            bridge.ingest_guest_frame(f);
        }
        bridge.poll(t_ms);
        while let Some(f) = bridge.next_host_frame() {
            guest_dev.push_rx(f);
        }
        guest_iface.poll(ts, guest_dev, guest_socks);
    }

    #[test]
    fn slirp_bridge_refuses_disallowed_dns_and_blocks_ssrf_metadata_syn() {
        let pol = EgressPolicy::default()
            .allow_domain("api.openai.com")
            .unwrap();
        let mut bridge = SlirpBridge::new(pol);
        let (mut g_dev, mut g_iface, mut g_socks) = make_guest();

        // 1. Guest sends UDP/53 DNS query for `evil.com` -> must receive REFUSED (RCODE=5)
        let udp_rx = udp::PacketBuffer::new(vec![udp::PacketMetadata::EMPTY; 4], vec![0; 1024]);
        let udp_tx = udp::PacketBuffer::new(vec![udp::PacketMetadata::EMPTY; 4], vec![0; 1024]);
        let mut g_udp = udp::Socket::new(udp_rx, udp_tx);
        g_udp.bind(40053).unwrap();
        let udp_h = g_socks.add(g_udp);

        let mut query = vec![
            0xAB, 0xCD, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        ];
        query.push(4);
        query.extend_from_slice(b"evil");
        query.push(3);
        query.extend_from_slice(b"com");
        query.push(0);
        query.extend_from_slice(&1u16.to_be_bytes());
        query.extend_from_slice(&1u16.to_be_bytes());

        g_socks
            .get_mut::<udp::Socket>(udp_h)
            .send_slice(&query, (IpAddress::Ipv4(GATEWAY_IP), 53))
            .unwrap();

        // 2. Guest also attempts TCP SYN to cloud metadata 169.254.169.254:80 (SSRF!)
        let tcp_rx = tcp::SocketBuffer::new(vec![0u8; 4096]);
        let tcp_tx = tcp::SocketBuffer::new(vec![0u8; 4096]);
        let tcp_h = g_socks.add(tcp::Socket::new(tcp_rx, tcp_tx));
        g_socks
            .get_mut::<tcp::Socket>(tcp_h)
            .connect(
                g_iface.context(),
                (IpAddress::v4(169, 254, 169, 254), 80),
                45001,
            )
            .unwrap();

        let mut dns_reply = None;
        for step in 0..20 {
            pump(&mut g_dev, &mut g_iface, &mut g_socks, &mut bridge, step * 10);
            if let Ok((data, _)) = g_socks.get_mut::<udp::Socket>(udp_h).recv() {
                dns_reply = Some(data.to_vec());
            }
        }

        let resp = dns_reply.expect("expected DNS REFUSED reply from SlirpBridge");
        assert_eq!(&resp[0..2], &[0xAB, 0xCD]);
        assert_eq!(resp[3] & 0x0F, 5, "expected RCODE=5 (REFUSED)");
        assert_eq!(bridge.stats.dns_blocked, 1);
        assert!(
            bridge.stats.tcp_blocked >= 1,
            "expected SSRF TCP SYN to 169.254.169.254:80 to be blocked"
        );
        assert_eq!(bridge.stats.tcp_allowed, 0);
    }

    #[test]
    fn slirp_bridge_relays_allowed_tcp_over_l2_ethernet_to_host() {
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        let port = listener.local_addr().unwrap().port();
        let server = thread::spawn(move || {
            if let Ok((mut s, _)) = listener.accept() {
                let mut buf = [0u8; 64];
                if let Ok(n) = s.read(&mut buf) {
                    let _ = s.write_all(&buf[..n]);
                }
            }
        });

        let pol = EgressPolicy::default()
            .allow_cidr(&format!("203.0.113.10/32:{port}"))
            .unwrap();
        let mut bridge = SlirpBridge::new(pol);
        bridge.upstream_override = Some(SocketAddr::new(IpAddr::V4(Ipv4Addr::LOCALHOST), port));
        let (mut g_dev, mut g_iface, mut g_socks) = make_guest();

        let tcp_rx = tcp::SocketBuffer::new(vec![0u8; 8192]);
        let tcp_tx = tcp::SocketBuffer::new(vec![0u8; 8192]);
        let tcp_h = g_socks.add(tcp::Socket::new(tcp_rx, tcp_tx));
        g_socks
            .get_mut::<tcp::Socket>(tcp_h)
            .connect(
                g_iface.context(),
                (IpAddress::v4(203, 0, 113, 10), port),
                45002,
            )
            .unwrap();

        let mut sent = false;
        let mut received = Vec::new();
        for step in 0..80 {
            pump(&mut g_dev, &mut g_iface, &mut g_socks, &mut bridge, step * 50);
            let s = g_socks.get_mut::<tcp::Socket>(tcp_h);
            if !sent && s.can_send() {
                s.send_slice(b"hello-over-smoltcp-l2").unwrap();
                sent = true;
            }
            if s.can_recv() {
                let chunk: Vec<u8> = s.recv(|b| (b.len(), b.to_vec())).unwrap();
                received.extend_from_slice(&chunk);
                if received.len() >= 21 {
                    break;
                }
            }
            thread::sleep(Duration::from_millis(1));
        }

        let g_state = g_socks.get::<tcp::Socket>(tcp_h).state();
        let b_states: Vec<_> = bridge
            .tcp_conns
            .iter()
            .map(|c| {
                (
                    c.dst_ip,
                    c.dst_port,
                    bridge.sockets.get::<tcp::Socket>(c.handle).state(),
                    matches!(c.upstream, UpstreamState::Connected(_)),
                )
            })
            .collect();
        assert_eq!(
            received,
            b"hello-over-smoltcp-l2",
            "stats={:?} g_state={:?} b_states={:?} sent={sent}",
            bridge.stats,
            g_state,
            b_states
        );
        assert_eq!(bridge.stats.tcp_allowed, 1);
        assert_eq!(bridge.stats.tcp_blocked, 0);
        let _ = server.join();
    }
}
