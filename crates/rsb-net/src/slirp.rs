//! Transparent pure-Rust L2/L3 userspace network bridge (`smoltcp` + `EgressPolicy`).
//!
//! Acts as a rootless slirp-like virtual gateway (`10.0.2.2/24`) for a sandboxed
//! `CLONE_NEWNET` namespace:
//! - Terminates Ethernet/ARP/IPv4/UDP/TCP in userspace via `smoltcp` (`any_ip = true`)
//!   so **even binaries that ignore `HTTP_PROXY`** are transparently filtered!
//! - **UDP/53 DNS Filter:** Intercepts DNS queries, rejects disallowed domains with
//!   RFC 1035 `REFUSED`, resolves allowed domains on the host, filters out SSRF IPs,
//!   and caches `Ipv4Addr -> domain` for subsequent TCP connections.
//! - **TCP L3/L4/SNI Bridge:** Inspects every incoming TCP `SYN` destination `(dst_ip, dst_port)`
//!   against `EgressPolicy` (including SSRF hard-block on `169.254.169.254`, `127.0.0.0/8`,
//!   RFC1918). Allowed connections are terminated in `smoltcp`, verified via `extract_tls_sni`
//!   on port 443, and relayed to a real host `TcpStream`.

